/**
 * 도면에서 온 글(도면층·블록·선종류·문자 스타일·치수 스타일·배치 이름, 속성 태그·값, 문자 내용, 경로 등)을 화면 번역층이 바꾸지 않게 하는 표시(104차).
 *
 * 화면 번역층(i18n.ts)은 DOM의 글 마디·속성을 사전(열쇠 8천여 개)으로 바꾼다. 도면 글은 파일이 정한 임의 글이라
 * ① 사전 열쇠와 같으면 통째로 바뀌고(도면층 "치수" → "Dimension"), ② 다른 언어 번역 글과 같으면 한국어 열쇠로 되찾아 바뀌고
 * (문자 스타일 "Standard" → 일본어 화면 "標準"), ③ 틀이 맞지 않는 글은 " · "·" — "로 나눈 조각마다 바뀌었다.
 *
 * - 도면 글만 담은 요소는 translate="no"로 뺀다(번역층의 SKIP).
 * - 앱 글과 섞을 때는 도면 글을 ft()로 감싼다(U+2068·U+2069 — 보이지 않는 양방향 격리 글자). 번역층의 지킴(fileguard.ts)이 감싼 자리를
 *   사용 영역 글자로 바꿔 옮긴 뒤 되돌리고 표시를 지운다(사전 틀의 {0}이 그 글자를 그대로 잡는다 — SKP 52차와 같은 방법).
 * 이 모듈은 아무것도 가져오지 않는다(편집 코드·워커 쪽에서 써도 번역층이 딸려 오지 않게).
 */

/** 도면 글 표시: 앱 글에 이어 붙일 때 이것으로 감싼다(화면 번역층이 옮기지 않는다). 번역층을 거치지 않는 글(복사·저장·비교)에는 쓰지 않는다 */
export const ft = (s: string): string => `⁨${s}⁩`;

/** ft() 표시를 뺀 글 */
export const unmark = (s: string): string => s.replace(/[⁨⁩]/g, '');
